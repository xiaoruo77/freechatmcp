param(
    [string]$Root = (Split-Path -Parent (Split-Path -Parent $PSScriptRoot)),
    [switch]$OpenExtensionsPage = $true
)

$ErrorActionPreference = 'Stop'

$ExtensionRoot = Join-Path $Root '10_web_deploy\edge_extension'
$TokenFile = Join-Path $Root '08_web_data\browser_bridge.token'
$ConfigFile = Join-Path $ExtensionRoot 'config.js'

if (-not (Test-Path -LiteralPath $ExtensionRoot)) {
    throw "Edge extension directory not found: $ExtensionRoot"
}
if (-not (Test-Path -LiteralPath $TokenFile)) {
    throw "Browser bridge token not found. Start the browser bridge once first: $Root\10_web_deploy\windows\start-browser-bridge.ps1"
}

$Token = (Get-Content -LiteralPath $TokenFile -Raw).Trim()
if ([string]::IsNullOrWhiteSpace($Token)) {
    throw "Browser bridge token is empty: $TokenFile"
}

$TokenJson = $Token | ConvertTo-Json -Compress
$Config = @"
// Generated by install-edge-extension.ps1. Do not commit this file.
globalThis.XIAORUO1_BRIDGE_TOKEN = $TokenJson;
"@
Set-Content -LiteralPath $ConfigFile -Value $Config -Encoding UTF8

$EdgeCandidates = @(
    (Join-Path ${env:ProgramFiles(x86)} 'Microsoft\Edge\Application\msedge.exe'),
    (Join-Path $env:ProgramFiles 'Microsoft\Edge\Application\msedge.exe')
) | Where-Object { $_ -and (Test-Path -LiteralPath $_) }

if ($OpenExtensionsPage -and @($EdgeCandidates).Count -gt 0) {
    $EdgePath = @($EdgeCandidates)[0]
    Start-Process -FilePath $EdgePath -ArgumentList 'edge://extensions/'
}

Write-Host "Generated Edge extension configuration: $ConfigFile"
Write-Host "Extension directory: $ExtensionRoot"
Write-Host "Next: Edge -> edge://extensions -> Developer mode -> Load unpacked -> select this directory."